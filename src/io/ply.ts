type ScalarType = 'i8' | 'u8' | 'i16' | 'u16' | 'i32' | 'u32' | 'f32' | 'f64';

const TYPE_ALIASES: Record<string, ScalarType> = {
  char: 'i8', int8: 'i8',
  uchar: 'u8', uint8: 'u8',
  short: 'i16', int16: 'i16',
  ushort: 'u16', uint16: 'u16',
  int: 'i32', int32: 'i32',
  uint: 'u32', uint32: 'u32',
  float: 'f32', float32: 'f32',
  double: 'f64', float64: 'f64',
};

const TYPE_SIZE: Record<ScalarType, number> = { i8: 1, u8: 1, i16: 2, u16: 2, i32: 4, u32: 4, f32: 4, f64: 8 };

interface PlyProperty {
  name: string;
  type: ScalarType;
  /** For list properties: the count type. */
  countType?: ScalarType;
}

interface PlyElement {
  name: string;
  count: number;
  props: PlyProperty[];
}

type Format = 'ascii' | 'binary_little_endian' | 'binary_big_endian';

function parseType(t: string): ScalarType {
  const s = TYPE_ALIASES[t];
  if (!s) throw new Error(`PLY: unknown property type '${t}'`);
  return s;
}

function findHeaderEnd(u8: Uint8Array): { headerEnd: number; bodyStart: number } {
  const pat = [101, 110, 100, 95, 104, 101, 97, 100, 101, 114]; // 'end_header'
  const limit = Math.min(u8.length - pat.length, 1 << 20);
  outer: for (let i = 0; i <= limit; i++) {
    for (let k = 0; k < pat.length; k++) if (u8[i + k] !== pat[k]) continue outer;
    // Must start a line.
    if (i > 0 && u8[i - 1] !== 10 && u8[i - 1] !== 13) continue;
    let j = i + pat.length;
    while (j < u8.length && (u8[j] === 32 || u8[j] === 9)) j++;
    if (u8[j] === 13) j++;
    if (u8[j] === 10) j++;
    return { headerEnd: i, bodyStart: j };
  }
  throw new Error('PLY: missing end_header');
}

function parseHeader(text: string): { format: Format; elements: PlyElement[]; comments: string[] } {
  const lines = text.split(/\r?\n|\r/);
  if (lines[0].trim() !== 'ply') throw new Error('PLY: missing magic');
  let format: Format | null = null;
  const elements: PlyElement[] = [];
  const comments: string[] = [];
  for (let li = 1; li < lines.length; li++) {
    const line = lines[li].trim();
    if (!line) continue;
    const tok = line.split(/\s+/);
    switch (tok[0]) {
      case 'format':
        if (tok[1] !== 'ascii' && tok[1] !== 'binary_little_endian' && tok[1] !== 'binary_big_endian') {
          throw new Error(`PLY: unsupported format '${tok[1]}'`);
        }
        format = tok[1];
        break;
      case 'comment':
        comments.push(line.slice(7).trim());
        break;
      case 'obj_info':
        break;
      case 'element': {
        const count = Number(tok[2]);
        if (!Number.isInteger(count) || count < 0) throw new Error(`PLY: bad element count in '${line}'`);
        elements.push({ name: tok[1], count, props: [] });
        break;
      }
      case 'property': {
        const el = elements[elements.length - 1];
        if (!el) throw new Error('PLY: property before element');
        if (tok[1] === 'list') el.props.push({ name: tok[4], countType: parseType(tok[2]), type: parseType(tok[3]) });
        else el.props.push({ name: tok[2], type: parseType(tok[1]) });
        break;
      }
      default:
        // Unknown header keyword: ignore (be liberal in what we accept).
        break;
    }
  }
  if (!format) throw new Error('PLY: missing format line');
  return { format, elements, comments };
}

/** Value source abstracting ascii / binary bodies. */
interface ValueStream {
  read(type: ScalarType): number;
}

class BinaryStream implements ValueStream {
  private dv: DataView;
  o: number;
  constructor(u8: Uint8Array, start: number, readonly le: boolean) {
    this.dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
    this.o = start;
  }
  read(type: ScalarType): number {
    const dv = this.dv;
    const o = this.o;
    if (o + TYPE_SIZE[type] > dv.byteLength) throw new Error('PLY: unexpected end of binary data');
    this.o = o + TYPE_SIZE[type];
    switch (type) {
      case 'f32': return dv.getFloat32(o, this.le);
      case 'u8': return dv.getUint8(o);
      case 'i32': return dv.getInt32(o, this.le);
      case 'u32': return dv.getUint32(o, this.le);
      case 'f64': return dv.getFloat64(o, this.le);
      case 'i8': return dv.getInt8(o);
      case 'i16': return dv.getInt16(o, this.le);
      case 'u16': return dv.getUint16(o, this.le);
    }
  }
}

class AsciiStream implements ValueStream {
  private o: number;
  constructor(private s: string, start: number) {
    this.o = start;
  }
  read(_type: ScalarType): number {
    const s = this.s;
    let i = this.o;
    const n = s.length;
    for (;;) {
      while (i < n) {
        const c = s.charCodeAt(i);
        if (c !== 32 && c !== 9 && c !== 10 && c !== 13) break;
        i++;
      }
      // Skip stray comment lines inside the body (some writers emit them).
      if (i < n && s.charCodeAt(i) === 35 /* # */) {
        while (i < n && s.charCodeAt(i) !== 10) i++;
        continue;
      }
      break;
    }
    if (i >= n) throw new Error('PLY: unexpected end of ascii data');
    const start = i;
    while (i < n) {
      const c = s.charCodeAt(i);
      if (c === 32 || c === 9 || c === 10 || c === 13) break;
      i++;
    }
    this.o = i;
    const v = Number(s.slice(start, i));
    if (Number.isNaN(v) && s.slice(start, i).toLowerCase() !== 'nan') throw new Error(`PLY: bad number '${s.slice(start, i)}'`);
    return v;
  }
}

/** Read one fixed-stride column into out[outOff + outStride*i]. Type switch hoisted out of the loop. */
function readColumn(
  dv: DataView, base: number, stride: number, type: ScalarType, le: boolean, n: number,
  out: Float32Array | Uint8Array, outStride: number, outOff: number,
): void {
  let o = base;
  let j = outOff;
  switch (type) {
    case 'f32': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getFloat32(o, le); break;
    case 'f64': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getFloat64(o, le); break;
    case 'u8': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getUint8(o); break;
    case 'i8': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getInt8(o); break;
    case 'u16': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getUint16(o, le); break;
    case 'i16': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getInt16(o, le); break;
    case 'u32': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getUint32(o, le); break;
    case 'i32': for (let i = 0; i < n; i++, o += stride, j += outStride) out[j] = dv.getInt32(o, le); break;
  }
}

const COLOR_NAMES: Record<string, number> = {
  red: 0, green: 1, blue: 2,
  r: 0, g: 1, b: 2,
  diffuse_red: 0, diffuse_green: 1, diffuse_blue: 2,
};
const POS_NAMES: Record<string, number> = { x: 0, y: 1, z: 2 };
const NORMAL_NAMES: Record<string, number> = { nx: 0, ny: 1, nz: 2, normal_x: 0, normal_y: 1, normal_z: 2 };

function colorScale(type: ScalarType): (v: number) => number {
  if (type === 'f32' || type === 'f64') return (v) => Math.max(0, Math.min(255, Math.round(v * 255)));
  if (type === 'u16' || type === 'i16') return (v) => Math.max(0, Math.min(255, Math.round(v / 257)));
  return (v) => Math.max(0, Math.min(255, v));
}

/** Decode an ascii / binary PLY point cloud or triangle mesh. */
export function decodePLY(input: ArrayBuffer | Uint8Array): PLYDecodeResult {
  const u8 = input instanceof Uint8Array ? input : new Uint8Array(input);
  const { headerEnd, bodyStart } = findHeaderEnd(u8);
  const headerText = new TextDecoder('latin1').decode(u8.subarray(0, headerEnd));
  const { format, elements, comments } = parseHeader(headerText);

  const stream: ValueStream =
    format === 'ascii'
      ? new AsciiStream(new TextDecoder('latin1').decode(u8.subarray(bodyStart)), 0)
      : new BinaryStream(u8, bodyStart, format === 'binary_little_endian');

  let positions: Float32Array | null = null;
  let colors: Uint8Array | null = null;
  let normals: Float32Array | null = null;
  let radii: Float32Array | null = null;
  let confidence: Float32Array | null = null;
  let vertexCount = 0;
  let hasFace = false;
  let tri: Uint32Array | null = null;
  let triCount = 0;

  for (const el of elements) {
    if (el.name === 'vertex') {
      const n = el.count;
      vertexCount = n;
      const props = el.props;
      // Per property: target array + component + transform.
      const kinds = new Int8Array(props.length).fill(-1); // 0 pos, 1 normal, 2 color, 3 radius, 4 conf
      const comps = new Int8Array(props.length);
      const cscale: ((v: number) => number)[] = [];
      let hasPos = 0;
      let hasNormal = 0;
      let hasColor = 0;
      props.forEach((p, k) => {
        if (p.countType) return;
        if (p.name in POS_NAMES) { kinds[k] = 0; comps[k] = POS_NAMES[p.name]; hasPos++; }
        else if (p.name in NORMAL_NAMES) { kinds[k] = 1; comps[k] = NORMAL_NAMES[p.name]; hasNormal++; }
        else if (p.name in COLOR_NAMES) { kinds[k] = 2; comps[k] = COLOR_NAMES[p.name]; hasColor++; cscale[k] = colorScale(p.type); }
        else if (p.name === 'radius') kinds[k] = 3;
        else if (p.name === 'confidence') kinds[k] = 4;
      });
      if (hasPos < 3) throw new Error('PLY: vertex element lacks x/y/z');
      positions = new Float32Array(3 * n);
      colors = new Uint8Array(3 * n);
      if (hasColor < 3) colors.fill(PLY_DEFAULT_GRAY);
      if (hasNormal === 3) normals = new Float32Array(3 * n);
      if (kinds.includes(3)) radii = new Float32Array(n);
      if (kinds.includes(4)) confidence = new Float32Array(n);
      const P = positions;
      const C = colors;
      const N = normals;
      const R = radii;
      const Q = confidence;
      const colorOk = hasColor >= 3;
      if (stream instanceof BinaryStream && props.every((p) => !p.countType)) {
        // Fast path: fixed stride, one tight loop per property (column).
        let stride = 0;
        const offs = props.map((p) => {
          const o = stride;
          stride += TYPE_SIZE[p.type];
          return o;
        });
        const base = stream.o;
        if (base + stride * n > u8.byteLength) throw new Error('PLY: unexpected end of binary data');
        const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
        props.forEach((p, k) => {
          const b = base + offs[k];
          switch (kinds[k]) {
            case 0: readColumn(dv, b, stride, p.type, stream.le, n, P, 3, comps[k]); break;
            case 1: if (N) readColumn(dv, b, stride, p.type, stream.le, n, N, 3, comps[k]); break;
            case 2:
              if (colorOk) {
                if (p.type === 'u8') readColumn(dv, b, stride, p.type, stream.le, n, C, 3, comps[k]);
                else {
                  const tmp = new Float32Array(n);
                  readColumn(dv, b, stride, p.type, stream.le, n, tmp, 1, 0);
                  const f = cscale[k];
                  for (let i = 0; i < n; i++) C[3 * i + comps[k]] = f(tmp[i]);
                }
              }
              break;
            case 3: readColumn(dv, b, stride, p.type, stream.le, n, R!, 1, 0); break;
            case 4: readColumn(dv, b, stride, p.type, stream.le, n, Q!, 1, 0); break;
            default: break;
          }
        });
        stream.o = base + stride * n;
        continue;
      }
      for (let i = 0; i < n; i++) {
        for (let k = 0; k < props.length; k++) {
          const p = props[k];
          if (p.countType) {
            const c = stream.read(p.countType);
            for (let j = 0; j < c; j++) stream.read(p.type);
            continue;
          }
          const v = stream.read(p.type);
          switch (kinds[k]) {
            case 0: P[3 * i + comps[k]] = v; break;
            case 1: if (N) N[3 * i + comps[k]] = v; break;
            case 2: if (colorOk) C[3 * i + comps[k]] = cscale[k](v); break;
            case 3: R![i] = v; break;
            case 4: Q![i] = v; break;
            default: break;
          }
        }
      }
    } else if (el.name === 'face') {
      hasFace = true;
      const listIdx = el.props.findIndex((p) => !!p.countType && p.name.startsWith('vertex_ind'));
      if (listIdx < 0 && el.count > 0) throw new Error('PLY: face element lacks vertex_indices list');
      let cap = Math.max(16, 3 * el.count);
      let T = new Uint32Array(cap);
      let m = 0;
      const poly: number[] = [];
      const lp = el.props[listIdx];
      if (
        stream instanceof BinaryStream &&
        el.props.length === 1 &&
        lp && (lp.countType === 'u8' || lp.countType === 'i8') && (lp.type === 'i32' || lp.type === 'u32')
      ) {
        // Fast path: binary 'list uchar int' faces (the common layout).
        const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
        const le = stream.le;
        let o = stream.o;
        const end = u8.byteLength;
        for (let i = 0; i < el.count; i++) {
          if (o + 1 > end) throw new Error('PLY: unexpected end of binary data');
          const c = dv.getUint8(o);
          o += 1;
          if (o + 4 * c > end) throw new Error('PLY: unexpected end of binary data');
          if (m + 3 * Math.max(0, c - 2) > cap) {
            while (m + 3 * Math.max(0, c - 2) > cap) cap *= 2;
            const T2 = new Uint32Array(cap);
            T2.set(T);
            T = T2;
          }
          const v0 = dv.getUint32(o, le);
          for (let j = 1; j + 1 < c; j++) {
            T[m++] = v0;
            T[m++] = dv.getUint32(o + 4 * j, le);
            T[m++] = dv.getUint32(o + 4 * j + 4, le);
          }
          o += 4 * c;
        }
        stream.o = o;
        tri = m === T.length ? T : T.slice(0, m);
        triCount = m / 3;
        continue;
      }
      for (let i = 0; i < el.count; i++) {
        for (let k = 0; k < el.props.length; k++) {
          const p = el.props[k];
          if (!p.countType) {
            stream.read(p.type);
            continue;
          }
          const c = stream.read(p.countType);
          if (k !== listIdx) {
            for (let j = 0; j < c; j++) stream.read(p.type);
            continue;
          }
          poly.length = 0;
          for (let j = 0; j < c; j++) poly.push(stream.read(p.type));
          for (let j = 1; j + 1 < c; j++) {
            if (m + 3 > cap) {
              cap *= 2;
              const T2 = new Uint32Array(cap);
              T2.set(T);
              T = T2;
            }
            T[m++] = poly[0];
            T[m++] = poly[j];
            T[m++] = poly[j + 1];
          }
        }
      }
      tri = m === T.length ? T : T.slice(0, m);
      triCount = m / 3;
    } else {
      // Skip unknown elements.
      for (let i = 0; i < el.count; i++) {
        for (const p of el.props) {
          if (p.countType) {
            const c = stream.read(p.countType);
            for (let j = 0; j < c; j++) stream.read(p.type);
          } else stream.read(p.type);
        }
      }
    }
  }

  if (!positions || !colors) {
    if (hasFace) throw new Error('PLY: faces without vertices');
    return { points: { count: 0, positions: new Float32Array(0), colors: new Uint8Array(0) }, comments };
  }

  if (hasFace) {
    const indices = tri ?? new Uint32Array(0);
    for (let i = 0; i < indices.length; i++) {
      if (indices[i] >= vertexCount) throw new RangeError(`PLY: face index ${indices[i]} out of range (${vertexCount} vertices)`);
    }
    return {
      mesh: {
        vertexCount,
        triangleCount: triCount,
        positions,
        normals: normals ?? computeVertexNormals(positions, indices, vertexCount),
        colors,
        indices,
      },
      comments,
    };
  }
  const pc: PointCloud = { count: vertexCount, positions, colors };
  if (normals) pc.normals = normals;
  if (radii) pc.radii = radii;
  if (confidence) pc.confidence = confidence;
  return { points: pc, comments };
}

/** Area-weighted vertex normals (unit; (0,0,1) for isolated vertices). */
export function computeVertexNormals(positions: Float32Array, indices: Uint32Array, vertexCount: number): Float32Array {
  const acc = new Float64Array(3 * vertexCount);
  const P = positions;
  for (let t = 0; t + 2 < indices.length; t += 3) {
    const a = 3 * indices[t];
    const b = 3 * indices[t + 1];
    const c = 3 * indices[t + 2];
    const ux = P[b] - P[a], uy = P[b + 1] - P[a + 1], uz = P[b + 2] - P[a + 2];
    const vx = P[c] - P[a], vy = P[c + 1] - P[a + 1], vz = P[c + 2] - P[a + 2];
    const nx = uy * vz - uz * vy;
    const ny = uz * vx - ux * vz;
    const nz = ux * vy - uy * vx;
    acc[a] += nx; acc[a + 1] += ny; acc[a + 2] += nz;
    acc[b] += nx; acc[b + 1] += ny; acc[b + 2] += nz;
    acc[c] += nx; acc[c + 1] += ny; acc[c + 2] += nz;
  }
  const out = new Float32Array(3 * vertexCount);
  for (let i = 0; i < vertexCount; i++) {
    const x = acc[3 * i], y = acc[3 * i + 1], z = acc[3 * i + 2];
    const l = Math.hypot(x, y, z);
    if (l > 0) {
      out[3 * i] = x / l;
      out[3 * i + 1] = y / l;
      out[3 * i + 2] = z / l;
    } else out[3 * i + 2] = 1;
  }
  return out;
}

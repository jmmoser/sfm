/**
 * PLY (Stanford polygon format) writer and reader.
 *
 * Writer (always binary_little_endian 1.0):
 *  - point cloud: `vertex` element with
 *      float x y z, [float nx ny nz], uchar red green blue, [float radius], [float confidence]
 *  - mesh: `vertex` element with float x y z nx ny nz, uchar red green blue, and a
 *      `face` element with `property list uchar int vertex_indices`.
 *  These layouts load in MeshLab, CloudCompare, Blender, Open3D and three.js.
 *
 * Reader: ascii, binary_little_endian and binary_big_endian; any scalar types;
 * recognises x/y/z, nx/ny/nz (or normal_x…), red/green/blue (or r/g/b,
 * diffuse_*; uchar, ushort or float 0..1), radius, confidence, and face lists
 * named vertex_indices / vertex_index (polygons are fan-triangulated). Other
 * elements and properties are skipped. If a `face` element exists the result is
 * a mesh (normals computed when absent), otherwise a point cloud.
 */
import type { PointCloud, TriangleMesh } from '../core/types';

export interface PLYEncodeOptions {
  /** Extra `comment` lines (newlines are stripped). */
  comments?: string[];
}

export interface PLYDecodeResult {
  points?: PointCloud;
  mesh?: TriangleMesh;
  /** `comment` lines from the header. */
  comments?: string[];
}

/** Colour assigned when a file has no per-vertex colour. */
export const PLY_DEFAULT_GRAY = 200;

const GENERATOR_COMMENT = 'generated by sfm (on-device photogrammetry)';

function headerBytes(lines: string[]): Uint8Array {
  return new TextEncoder().encode(lines.join('\n') + '\n');
}

function commentLines(opts: PLYEncodeOptions | undefined): string[] {
  const out = [`comment ${GENERATOR_COMMENT}`];
  for (const c of opts?.comments ?? []) out.push(`comment ${c.replace(/[\r\n]+/g, ' ')}`);
  return out;
}

function assertLen(a: ArrayLike<number> | undefined, n: number, what: string): void {
  if (a && a.length < n) throw new RangeError(`PLY: ${what} has ${a.length} values, need ${n}`);
}

/** Binary little-endian PLY of a point cloud. */
export function encodePLY(pc: PointCloud, opts?: PLYEncodeOptions): ArrayBuffer {
  const n = pc.count;
  assertLen(pc.positions, 3 * n, 'positions');
  assertLen(pc.colors, 3 * n, 'colors');
  assertLen(pc.normals, 3 * n, 'normals');
  assertLen(pc.radii, n, 'radii');
  assertLen(pc.confidence, n, 'confidence');
  const hasN = !!pc.normals;
  const hasR = !!pc.radii;
  const hasC = !!pc.confidence;

  const lines = ['ply', 'format binary_little_endian 1.0', ...commentLines(opts), `element vertex ${n}`];
  lines.push('property float x', 'property float y', 'property float z');
  if (hasN) lines.push('property float nx', 'property float ny', 'property float nz');
  lines.push('property uchar red', 'property uchar green', 'property uchar blue');
  if (hasR) lines.push('property float radius');
  if (hasC) lines.push('property float confidence');
  lines.push('end_header');
  const header = headerBytes(lines);

  const stride = 12 + (hasN ? 12 : 0) + 3 + (hasR ? 4 : 0) + (hasC ? 4 : 0);
  const buf = new ArrayBuffer(header.length + stride * n);
  new Uint8Array(buf).set(header);
  const dv = new DataView(buf);
  const P = pc.positions;
  const C = pc.colors;
  const N = pc.normals;
  const R = pc.radii;
  const Q = pc.confidence;
  let o = header.length;
  for (let i = 0; i < n; i++) {
    const i3 = 3 * i;
    dv.setFloat32(o, P[i3], true);
    dv.setFloat32(o + 4, P[i3 + 1], true);
    dv.setFloat32(o + 8, P[i3 + 2], true);
    o += 12;
    if (N) {
      dv.setFloat32(o, N[i3], true);
      dv.setFloat32(o + 4, N[i3 + 1], true);
      dv.setFloat32(o + 8, N[i3 + 2], true);
      o += 12;
    }
    dv.setUint8(o, C[i3]);
    dv.setUint8(o + 1, C[i3 + 1]);
    dv.setUint8(o + 2, C[i3 + 2]);
    o += 3;
    if (R) {
      dv.setFloat32(o, R[i], true);
      o += 4;
    }
    if (Q) {
      dv.setFloat32(o, Q[i], true);
      o += 4;
    }
  }
  return buf;
}

/** Binary little-endian PLY of a triangle mesh (vertex normals + colours, int indices). */
export function encodeMeshPLY(mesh: TriangleMesh, opts?: PLYEncodeOptions): ArrayBuffer {
  const nv = mesh.vertexCount;
  const nt = mesh.triangleCount;
  assertLen(mesh.positions, 3 * nv, 'positions');
  assertLen(mesh.normals, 3 * nv, 'normals');
  assertLen(mesh.colors, 3 * nv, 'colors');
  assertLen(mesh.indices, 3 * nt, 'indices');

  const lines = ['ply', 'format binary_little_endian 1.0', ...commentLines(opts), `element vertex ${nv}`];
  lines.push('property float x', 'property float y', 'property float z');
  lines.push('property float nx', 'property float ny', 'property float nz');
  lines.push('property uchar red', 'property uchar green', 'property uchar blue');
  lines.push(`element face ${nt}`, 'property list uchar int vertex_indices', 'end_header');
  const header = headerBytes(lines);

  const buf = new ArrayBuffer(header.length + 27 * nv + 13 * nt);
  new Uint8Array(buf).set(header);
  const dv = new DataView(buf);
  const P = mesh.positions;
  const N = mesh.normals;
  const C = mesh.colors;
  let o = header.length;
  for (let i = 0; i < nv; i++) {
    const i3 = 3 * i;
    dv.setFloat32(o, P[i3], true);
    dv.setFloat32(o + 4, P[i3 + 1], true);
    dv.setFloat32(o + 8, P[i3 + 2], true);
    dv.setFloat32(o + 12, N[i3], true);
    dv.setFloat32(o + 16, N[i3 + 1], true);
    dv.setFloat32(o + 20, N[i3 + 2], true);
    dv.setUint8(o + 24, C[i3]);
    dv.setUint8(o + 25, C[i3 + 1]);
    dv.setUint8(o + 26, C[i3 + 2]);
    o += 27;
  }
  const I = mesh.indices;
  for (let t = 0; t < nt; t++) {
    const a = I[3 * t];
    const b = I[3 * t + 1];
    const c = I[3 * t + 2];
    if (a >= nv || b >= nv || c >= nv) throw new RangeError(`PLY: triangle ${t} references vertex ≥ ${nv}`);
    dv.setUint8(o, 3);
    dv.setInt32(o + 1, a, true);
    dv.setInt32(o + 5, b, true);
    dv.setInt32(o + 9, c, true);
    o += 13;
  }
  return buf;
}

